/*
 * Transcoding tests for the netlogon coders. See coder-test.h for the
 * tests run per case.
 *
 * Where the known-good NDR stubs come from (ad-adc, a Windows Server 2016
 * domain controller, for the workstation account NLTEST1$):
 *
 * - ReqChallenge and Authenticate3 replies were captured from the server.
 *   Windows always replies in its native format, so there are only NDR32
 *   and NDR64 little-endian ones.
 * - Those requests were encoded by libdcerpc and sent to the server, which
 *   accepted them as NDR32 LE, NDR32 BE and NDR64 LE. Windows does not
 *   support NDR64 BE.
 * - Each flavor ran ReqChallenge and then Authenticate3 on one
 *   \\pipe\\netlogon connection, with the AES credentials computed from
 *   the account password; the server credential in each reply checked
 *   out. The server challenge, and so both credentials, differ per run,
 *   hence one case per flavor for those.
 *
 * LogonGetCapabilities is the first call that needs the secure channel.
 * A DC rejects it until the PDU is signed, so these stubs are the
 * library's own encoding of one request and one reply, in every flavor,
 * including NDR64 BE. The reply takes QueryLevel from its request.
 *
 * ServerPasswordSet2 is the same kind of vector. ClearNewPassword is a
 * fixed 512-byte buffer plus a length; the caller encrypts it, so the
 * coder test uses a stand-in buffer (0x5a, with the eight bytes
 * "password" at the end and Length 8).
 *
 * LogonGetDomainInfo level 1 is the same kind of vector. The workstation
 * buffer names the host and leaves the other strings empty. The reply is
 * one domain, with no trusted domains and no domain SID. The reply takes
 * Level from its request.
 *
 * LogonSamLogonEx is a network logon (level 2) asking for SamInfo4
 * (validation level 6). The NT challenge response is eight 0x11 bytes and
 * the LM response is empty. The reply has one group, the domain SID
 * S-1-5-21-1-2-3 and one extra SID. The reply takes ValidationLevel from
 * its request.
 */

