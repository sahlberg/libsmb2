/*
 * Transcoding tests for the lsa coders: the request and reply of every
 * operation, OpenPolicy2 with and without SECURITY_QUALITY_OF_SERVICE,
 * every QueryInformationPolicy information class, and lookups that
 * translate some names and SIDs and not others. See coder-test.h for the
 * tests run per case.
 *
 * Where the known-good NDR stubs come from (win16-1, Windows Server 2016):
 *
 * - Replies were captured from the server. Windows always replies in its
 *   native format, so there are only NDR32 and NDR64 little-endian ones.
 * - Requests were encoded by libdcerpc and sent to the server, which
 *   accepted them as NDR32 LE, NDR32 BE and NDR64 LE and answered each
 *   flavor alike apart from the context handles. Windows does not support
 *   NDR64 BE.
 * - The calls ran as two chains per flavor. The first: OpenPolicy2,
 *   LookupSids2 for BUILTIN\Administrators, Everyone, the local
 *   Administrator and an unknown SID, LookupNames2 for Administrator,
 *   Everyone and an unknown name (both STATUS_SOME_NOT_MAPPED), Close, and
 *   OpenPolicy2 with a SECURITY_QUALITY_OF_SERVICE followed by Close. The
 *   second: OpenPolicy, QueryInformationPolicy for every information
 *   class (some fail with STATUS_ACCESS_DENIED or
 *   STATUS_INVALID_PARAMETER, and then have no PolicyInformation),
 *   QueryInformationPolicy2 for three of them, EnumerateTrustedDomains
 *   (STATUS_NO_MORE_ENTRIES, win16-1 has no trusts), LookupNames,
 *   LookupSids and LookupNames3 with the same names and SIDs as above,
 *   GetUserName and Close.
 *
 * The lookup replies are marked XFAIL: Windows sets the MaximumLength of
 * their names to Length + 2, which libdcerpc does not keep because these
 * strings are char *, so they re-encode with MaximumLength = Length.
 *
 * The data was generated from the captures; cases whose captures differ
 * in live values are split into one case per capture.
 */

