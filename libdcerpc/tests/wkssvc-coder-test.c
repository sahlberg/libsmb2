/*
 * Transcoding tests for the wkssvc coders: every request and reply
 * structure, and every arm of the WKSTA_INFO, WKSTA_USER_ENUM_UNION and
 * USE_ENUM_UNION unions. See coder-test.h for the tests run per case.
 *
 * Where the known-good NDR stubs come from (win16-1, Windows Server 2016):
 *
 * - Replies were captured from the server. Windows always replies in its
 *   native format, so there are only NDR32 and NDR64 little-endian ones.
 * - Requests were encoded by libdcerpc and sent to the server, which
 *   accepted them as NDR32 LE, NDR32 BE and NDR64 LE: it answered with the
 *   same reply for each flavor rather than faulting with
 *   RPC_X_BAD_STUB_DATA. Windows does not support NDR64 BE and faults
 *   every NDR64 BE request. NetrWkstaSetInfo for levels 100, 101 and 102
 *   returns ERROR_INVALID_LEVEL, which comes from the server routine after
 *   the stub was unmarshalled.
 * - NetrUseEnum is refused with an access-denied fault before the stub is
 *   unmarshalled, and the server has no logged-on users for
 *   NetrWkstaUserEnum to list. Those cases, and the replies with
 *   populated lists, have known-good YAML only.
 *
 * The data was generated from the captures; replies whose NDR32 and NDR64
 * captures differ in live values are split into one case per capture.
 */

