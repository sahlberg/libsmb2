/*
 * Transcoding tests for the epm coders, generated from epm.idl with the
 * tower and annotation built-in types from dcerpc-epm.c: ept_lookup with a
 * reply of four entries (a tower and an empty annotation each), ept_map
 * for the svcctl interface over ncacn_ip_tcp with a reply of one tower,
 * and ept_lookup_handle_free. See coder-test.h for the tests run per case.
 *
 * Where the known-good NDR stubs come from (win16-1, Windows Server 2016):
 * the reply was captured from the server's endpoint mapper, which always
 * replies in its native format (NDR32 and NDR64 little-endian); the
 * request was encoded by libdcerpc and accepted by the server as NDR32 LE,
 * NDR32 BE and NDR64 LE. Windows does not support NDR64 BE.
 *
 * The reply coders size their arrays from the request's MaxEnts and
 * MaxTowers, so those reply cases have a request with the value sent (4).
 *
 * epm's object, interface and tower pointers are full pointers ([ptr]).
 * Their referent ids are 1, 2, ... in a request, and a reply continues
 * after the highest one of its request: the ept_map request's MapTower is
 * 1, so the tower in its reply is 2 (full_ptr_base). Windows faults an
 * NDR64 ept_map request whose full pointer has any other kind of id with
 * RPC_X_BAD_STUB_DATA.
 *
 * The data was generated from the captures; cases whose captures differ
 * in live values are split into one case per capture.
 */

